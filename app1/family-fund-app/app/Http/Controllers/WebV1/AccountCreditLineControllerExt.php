    /**
     * Admin gate for read-only credit-line endpoints.
     *
     * Wave-2 review (2026-05-14) flagged that index/show/create/edit had no
     * is_admin() check — only `simulator()` did. A non-admin authenticated
     * user could GET other accounts' credit-line data. Mirror the simulator
     * gate pattern here as a shared helper.
     */
    private function ensureAdmin(): void
    {
        if (!auth()->user()?->is_admin()) {
            abort(403);
        }
    }

    public function index($accountId, Request $request)
    {
        $this->ensureAdmin();
        $account = AccountExt::findOrFail($accountId);
        $this->authorize('viewAny', [AccountCreditLineExt::class, $account]);

        $nickname = trim((string) $request->query('nickname', ''));

        $lines = AccountCreditLine::where('account_id', $account->id)
            ->when($nickname !== '', fn ($q) => $q->where('nickname', 'like', '%' . $nickname . '%'))
            ->orderByDesc('id')
            ->get();

        return view('account_credit_lines.index')
            ->with('account', $account)
            ->with('lines', $lines)
            ->with('nickname', $nickname);
    }

    /**
     * Global (cross-account) credit-line listing. Admin-only.
     */
    public function globalIndex(Request $request)
    {
        $this->ensureAdmin();

        $nickname = trim((string) $request->query('nickname', ''));

        $lines = AccountCreditLine::with('account')
            ->when($nickname !== '', fn ($q) => $q->where('nickname', 'like', '%' . $nickname . '%'))
            ->orderByRaw("FIELD(status, 'active') DESC")
            ->orderByDesc('id')
            ->get();

        return view('account_credit_lines.global_index')
            ->with('lines', $lines)
            ->with('nickname', $nickname);
    }

    /**
     * Global (cross-account) open/late receivables listing. Admin-only.
     *
     * Shows every schedule row that is still open (scheduled / partial /
     * late) so the operator can see — and reconcile — the outstanding
     * backlog, including rows generated by backdated draws.
     */
    public function globalPayments(Request $request)
    {
        $this->ensureAdmin();

        $openStatuses = [
            CreditLinePayment::STATUS_SCHEDULED,
            CreditLinePayment::STATUS_PARTIAL,
            CreditLinePayment::STATUS_LATE,
        ];

        $allStatuses = [
            CreditLinePayment::STATUS_SCHEDULED,
            CreditLinePayment::STATUS_PARTIAL,
            CreditLinePayment::STATUS_LATE,
            CreditLinePayment::STATUS_PAID,
            CreditLinePayment::STATUS_CANCELLED,
        ];

        // 'open' (default) keeps the original open-receivables view; a
        // specific status narrows to it; 'all' shows everything.
        $status    = $request->query('status', 'open');
        $accountId = $request->query('account_id');
        $fundId    = $request->query('fund_id');
        $nickname  = trim((string) $request->query('nickname', ''));

        $query = CreditLinePayment::with(['creditLine.account.fund'])
            ->orderBy('due_date');

        if ($status === 'open') {
            $query->whereIn('status', $openStatuses);
        } elseif ($status !== 'all') {
            $query->where('status', $status);
        }

        if ($nickname !== '') {
            $query->whereHas('creditLine', fn ($q) => $q->where('nickname', 'like', '%' . $nickname . '%'));
        }
        if ($accountId) {
            $query->whereHas('creditLine', fn ($q) => $q->where('account_id', $accountId));
        }
        if ($fundId) {
            $query->whereHas('creditLine.account', fn ($q) => $q->where('fund_id', $fundId));
        }

        // Filter option lists: only accounts/funds that actually have
        // credit lines, so the dropdowns stay scoped to relevant choices.
        $accounts = AccountExt::whereIn('id', AccountCreditLine::query()->select('account_id'))
            ->with('fund')
            ->orderBy('nickname')
            ->get();
        $funds = $accounts->pluck('fund')
            ->filter()
            ->unique('id')
            ->sortBy('name')
            ->values();

        return view('account_credit_lines.global_payments')
            ->with('payments', $query->get())
            ->with('status', $status)
            ->with('statusOptions', $allStatuses)
            ->with('accounts', $accounts)
            ->with('funds', $funds)
            ->with('accountId', $accountId)
            ->with('fundId', $fundId)
            ->with('nickname', $nickname)
            ->with('today', Carbon::today());
    }

    public function create($accountId, OutstandingCalculator $calculator)
    {
        $this->ensureAdmin();
        $account = AccountExt::findOrFail($accountId);
        $this->authorize('create', [AccountCreditLineExt::class, $account]);

        $available = $calculator->availableToBorrow($account, Carbon::today());

        return view('account_credit_lines.create')
            ->with('account', $account)
            ->with('available', round($available, 4));
    }

    /**
     * JSON: available-to-borrow shares for an account as of a given date.
     *
     * Backs the create form's live "available shares" readout — when the
     * origination date changes (e.g. a backdated draw) the borrow cap is
     * recomputed against the OWN balance as of that date.
     */
    public function availableShares($accountId, Request $request, OutstandingCalculator $calculator)
    {
        $this->ensureAdmin();
        $account = AccountExt::findOrFail($accountId);
        $this->authorize('create', [AccountCreditLineExt::class, $account]);

        $asOf = $request->query('as_of');
        try {
            $date = !empty($asOf) ? Carbon::parse($asOf) : Carbon::today();
        } catch (\Throwable $e) {
            $date = Carbon::today();
        }
        if ($date->gt(Carbon::today())) {
            $date = Carbon::today();
        }

        return response()->json([
            'as_of'     => $date->toDateString(),
            'available' => round($calculator->availableToBorrow($account, $date), 4),
        ]);
    }

