    public function store(CreateAccountCreditLineRequest $request)
    {
        $data = $request->validated();
        $account = AccountExt::findOrFail($data['account_id']);
        $this->authorize('create', [AccountCreditLineExt::class, $account]);

        $originationDate = !empty($data['origination_date'])
            ? Carbon::parse($data['origination_date'])
            : null;
        $isBackdated = $originationDate !== null
            && $originationDate->lt(Carbon::today());

        try {
            $line = $this->drawService->open(
                $account,
                (float) $data['principal_shares'],
                (int) $data['term_months'],
                $data['payment_frequency'],
                $data['descr'] ?? null,
                $originationDate,
                $data['nickname']
            );
        } catch (OverBorrowException $e) {
            Flash::error($e->getMessage());
            return redirect()->back()->withInput();
        } catch (InvalidArgumentException $e) {
            // OutstandingCalculator's backdate guard: the chosen date predates
            // an existing open BOR balance row for this account. FF cannot
            // splice a draw before already-recorded borrow history.
            Flash::error(
                'Cannot backdate to ' . $originationDate?->toDateString()
                . ': the account already has recorded borrow activity on or after that date. '
                . 'Choose a later origination date. (' . $e->getMessage() . ')'
            );
            return redirect()->back()->withInput();
        }

        if ($isBackdated) {
            $lateCount = $line->payments()
                ->where('status', \App\Models\CreditLinePayment::STATUS_LATE)
                ->count();
            Flash::warning(
                'Credit line #' . $line->id . ' backdated to ' . $originationDate->toDateString()
                . '. ' . $lateCount . ' payment row(s) are already past due and flagged late. '
                . 'FamilyFund will not settle them — register any payments that already '
                . 'happened from the schedule below.'
            );
        }

        Flash::success('Credit line #' . $line->id . ' opened.');

        return redirect(route('credit_lines.show', ['line' => $line->id]));
    }

    public function show(
        $id,
        TrajectoryBuilder $trajectoryBuilder,
        LoansSummaryBuilder $loansSummaryBuilder,
        ScheduleSnapshotBuilder $snapshotBuilder
    ) {
        $this->ensureAdmin();
        $line = AccountCreditLineExt::findOrFail($id);
        $this->authorize('view', $line);
        $account = $line->account()->first();
        $history = $this->historyBuilder->build($line);
        $schedule = $line->payments()->orderBy('due_date')->get();
        $trajectory = $trajectoryBuilder->build($line);
        $loansSummary = $account ? $loansSummaryBuilder->forAccount($account) : [];

        // Build per-adjustment schedule snapshots so the timeline can render
        // an inline "View schedule at this point" modal for each adjustment
        // (Phase 4, deferred from Phase 3).
        $scheduleSnapshots = [];
        foreach ($history as $entry) {
            if (($entry['kind'] ?? null) !== 'adjustment') {
                continue;
            }
            $adjId = $entry['data']['id'] ?? null;
            $adjAt = $entry['data']['adjusted_at'] ?? $entry['date'] ?? null;
            if ($adjId && $adjAt) {
                $scheduleSnapshots[$adjId] = $snapshotBuilder->snapshotAt($line, $adjAt);
            }
        }

        // $-value of each schedule row at the share price of its due date
        // ("price of the day"). Only for rows whose due date has already
        // passed — a future row's price isn't known yet. Cached per distinct
        // date so a 480-row schedule doesn't fan out one query per row.
        $today = Carbon::today();
        $priceCache = [];
        $scheduleDollars = [];
        foreach ($schedule as $scheduleRow) {
            $due = Carbon::parse($scheduleRow->due_date);
            if ($due->gt($today)) {
                continue;
            }
            $key = $due->toDateString();
            if (!array_key_exists($key, $priceCache)) {
                try {
                    $priceCache[$key] = (float) ($account?->shareValueAsOf($key) ?? 0);
                } catch (\Throwable $e) {
                    $priceCache[$key] = 0.0;
                }
            }
            if ($priceCache[$key] > 0) {
                $scheduleDollars[$scheduleRow->id] = $scheduleRow->shares_due * $priceCache[$key];
            }
        }

        return view('account_credit_lines.show')
            ->with('line', $line)
            ->with('account', $account)
            ->with('schedule', $schedule)
            ->with('scheduleDollars', $scheduleDollars)
            ->with('history', $history)
            ->with('trajectory', $trajectory)
            ->with('loansSummary', $loansSummary)
            ->with('scheduleSnapshots', $scheduleSnapshots);
    }

