    /**
     * Apply an edit to an already-registered payment.
     *
     * Reverse (de-register) and re-register run inside a single DB transaction,
     * so the schedule row is only ever deregistered as part of the same commit
     * that re-registers it with the corrected values. If anything fails — or
     * the admin never reaches this endpoint — the original payment is untouched.
     */
    public function updatePayment(RegisterCreditLinePaymentRequest $request, $lineId, $paymentId)
    {
        $this->ensureAdmin();
        $line = AccountCreditLineExt::findOrFail($lineId);
        $this->authorize('process', $line);

        $row = CreditLinePayment::where('id', $paymentId)
            ->where('account_credit_line_id', $line->id)
            ->firstOrFail();

        if (!$row->paid_transaction_id) {
            Flash::error('Schedule row #' . $row->id . ' has no registered payment to edit.');
            return redirect(route('credit_lines.show', ['line' => $line->id]));
        }

        $oldTran = TransactionExt::findOrFail($row->paid_transaction_id);

        /** @var UserExt|null $admin */
        $admin = auth()->user();
        if ($admin && !$admin instanceof UserExt) {
            $admin = UserExt::find($admin->id);
        }

        $data = $request->validated();
        $date = !empty($data['date']) ? Carbon::parse($data['date']) : null;

        $reason = trim((string) $request->input('reason'));
        if ($reason === '') {
            $reason = 'Editing registered payment on schedule row #' . $row->id
                . ' (atomic reverse + re-register).';
        }

        try {
            $newTran = DB::transaction(function () use ($oldTran, $admin, $reason, $row, $data, $date) {
                $this->reverseService->reverse($oldTran, $admin, $reason);
                // Row state was reopened by the reverse above; re-register with
                // the corrected values in the same transaction.
                $row->refresh();
                return $this->repayService->repayRow($row, (float) $data['shares'], $date);
            });
        } catch (AlreadyReversedException $e) {
            Flash::error($e->getMessage());
            return redirect(route('credit_lines.show', ['line' => $line->id]));
        } catch (InvalidArgumentException $e) {
            Flash::error($e->getMessage());
            return redirect(route('credit_lines.payments.edit_form', [
                'line'    => $line->id,
                'payment' => $row->id,
            ]));
        }

        Flash::success(
            'Payment on schedule row #' . $row->id
            . ' updated (was txn #' . $oldTran->id . ', now txn #' . $newTran->id . ').'
        );

        return redirect(route('credit_lines.show', ['line' => $line->id]));
    }

    /**
     * Reverse a registered payment on a schedule row (the "Delete" / "Edit"
     * controls on the schedule and Receivables lists).
     *
     * Reverses the row's REP transaction via ReverseService — which re-opens
     * every row that transaction had satisfied (a cascaded over-payment can
     * touch several) and restores the line's outstanding. With `then=edit`
     * the admin is sent straight to the register form to re-enter correct
     * values; otherwise we return to the page they came from.
     */
    public function reversePayment(Request $request, $lineId, $paymentId)
    {
        $this->ensureAdmin();
        $line = AccountCreditLineExt::findOrFail($lineId);
        $this->authorize('process', $line);

        $row = CreditLinePayment::where('id', $paymentId)
            ->where('account_credit_line_id', $line->id)
            ->firstOrFail();

        if (!$row->paid_transaction_id) {
            Flash::error('Schedule row #' . $row->id . ' has no registered payment to reverse.');
            return redirect()->back();
        }

        $tran = TransactionExt::findOrFail($row->paid_transaction_id);

        /** @var UserExt|null $admin */
        $admin = auth()->user();
        if ($admin && !$admin instanceof UserExt) {
            $admin = UserExt::find($admin->id);
        }

        $isEdit = $request->input('then') === 'edit';
        $reason = trim((string) $request->input('reason'));
        if ($reason === '') {
            $reason = $isEdit
                ? 'Editing mis-registered payment on schedule row #' . $row->id . ' (reverse + re-register).'
                : 'Deleting mis-registered payment on schedule row #' . $row->id . '.';
        }

        try {
            $reversal = $this->reverseService->reverse($tran, $admin, $reason);
        } catch (AlreadyReversedException $e) {
            Flash::error($e->getMessage());
            return redirect()->back();
        }

        Flash::success(
            'Payment on schedule row #' . $row->id
            . ' reversed (txn #' . $tran->id . ', reversal #' . $reversal->id . ').'
        );

        if ($isEdit) {
            return redirect(route('credit_lines.payments.register_form', [
                'line'    => $line->id,
                'payment' => $row->id,
            ]));
        }

        return redirect()->back();
    }

    /**
     * Form to manually (re-)allocate a REP transaction's shares across the
     * line's schedule rows.
     *
     * Used when a payment can't be matched 1:1 to an installment (an
     * intentional split, or an unmatched payment the operator must place by
     * hand). Submitting replaces this transaction's existing allocations.
     */
    public function allocateForm($lineId, $transactionId)
    {
        $this->ensureAdmin();
        $line = AccountCreditLineExt::findOrFail($lineId);
        $this->authorize('process', $line);

        $tran = TransactionExt::where('id', $transactionId)
            ->where('account_credit_line_id', $line->id)
            ->where('type', TransactionExt::TYPE_REPAY)
            ->firstOrFail();

        if ($tran->reversed) {
            Flash::error('Transaction #' . $tran->id . ' is reversed and cannot be allocated.');
            return redirect(route('credit_lines.show', ['line' => $line->id]));
        }

        $rows = $line->payments()
            ->where('status', '!=', CreditLinePayment::STATUS_CANCELLED)
            ->orderBy('due_date')
            ->get();

        $currentAlloc = $tran->creditLineAllocations()
            ->pluck('shares', 'credit_line_payment_id')
            ->toArray();

        // Per-row contribution from OTHER transactions — used to display the
        // remainder this txn could still fill (shares_due - other = remainder).
        $otherAlloc = \App\Models\CreditLinePaymentAllocation::whereIn('credit_line_payment_id', $rows->pluck('id'))
            ->where('transaction_id', '!=', $tran->id)
            ->selectRaw('credit_line_payment_id, SUM(shares) as total')
            ->groupBy('credit_line_payment_id')
            ->pluck('total', 'credit_line_payment_id')
            ->map(fn ($v) => round((float) $v, 4))
            ->toArray();

        $account = $line->account()->with('fund')->first();

        return view('account_credit_lines.allocate_payment')
            ->with('line', $line)
            ->with('tran', $tran)
            ->with('rows', $rows)
            ->with('currentAlloc', $currentAlloc)
            ->with('otherAlloc', $otherAlloc)
            ->with('account', $account);
    }

    /**
     * Apply a manual (re-)allocation: replace this transaction's allocations
     * with the admin-entered per-row split.
     *
     * outstanding_shares is transaction-based and untouched; only the row
     * provenance/status changes (re-derived by PaymentAllocator).
     */
    public function allocate(Request $request, $lineId, $transactionId)
    {
        $this->ensureAdmin();
        $line = AccountCreditLineExt::findOrFail($lineId);
        $this->authorize('process', $line);

        $tran = TransactionExt::where('id', $transactionId)
            ->where('account_credit_line_id', $line->id)
            ->where('type', TransactionExt::TYPE_REPAY)
            ->firstOrFail();

        if ($tran->reversed) {
            Flash::error('Transaction #' . $tran->id . ' is reversed and cannot be allocated.');
            return redirect(route('credit_lines.show', ['line' => $line->id]));
        }

        $request->validate([
            'allocations'   => 'array',
            'allocations.*' => 'nullable|numeric|min:0',
        ]);

        // Keep only positive entries for rows that belong to this line and
        // are not cancelled.
        $validRowIds = $line->payments()
            ->where('status', '!=', CreditLinePayment::STATUS_CANCELLED)
            ->pluck('id')
            ->all();

        $split = [];
        foreach ((array) $request->input('allocations', []) as $rowId => $shares) {
            $shares = round((float) $shares, 4);
            if ($shares > 0 && in_array((int) $rowId, $validRowIds, true)) {
                $split[(int) $rowId] = $shares;
            }
        }

        $total      = round(array_sum($split), 4);
        $tranShares = round((float) $tran->shares, 4);
        if (abs($total - $tranShares) > 1e-4) {
            Flash::error(sprintf(
                'Allocations total %.4f but the transaction has %.4f shares — every share must land on a row. Use "Fill remainders" to auto-distribute.',
                $total, $tranShares
            ));
            return redirect(route('credit_lines.payments.allocate_form', [
                'line' => $line->id, 'transaction' => $tran->id,
            ]));
        }

        DB::transaction(function () use ($tran, $line, $split) {
            // Re-allocation semantics: drop this tx's prior allocations, then
            // apply the new split (a no-op deallocate is harmless).
            $this->allocator->deallocate($tran);
            $this->allocator->allocate($tran, $line, null, $split);
        });

        Flash::success(sprintf(
            'Allocated %.4f of txn #%d\'s %.4f shares across %d row(s).',
            $total, $tran->id, $tranShares, count($split)
        ));

        return redirect(route('credit_lines.show', ['line' => $line->id]));
    }

    public function readjust(ReadjustCreditLineRequest $request)
    {
        $data = $request->validated();
        $line = AccountCreditLineExt::findOrFail($data['account_credit_line_id']);
        $this->authorize('process', $line);

        /** @var UserExt|null $admin */
        $admin = auth()->user();
        if ($admin && !$admin instanceof UserExt) {
            $admin = UserExt::find($admin->id);
        }

        try {
            $adj = $this->readjustService->readjust(
                $line,
                isset($data['new_term_months']) ? (int) $data['new_term_months'] : null,
                $data['new_payment_frequency'] ?? null,
                $admin,
                $data['reason'] ?? null,
                !empty($data['effective_date']) ? Carbon::parse($data['effective_date']) : null
            );
        } catch (NoChangeException $e) {
            Flash::error($e->getMessage());
            return redirect()->back()->withInput();
        }

        Flash::success('Credit line readjusted (adjustment #' . $adj->id . ').');

        return redirect(route('credit_lines.show', ['line' => $line->id]));
    }

    public function cancel(CancelCreditLineRequest $request)
    {
        $data = $request->validated();
        $line = AccountCreditLineExt::findOrFail($data['account_credit_line_id']);
        $this->authorize('delete', $line);

        try {
            $this->cancelService->cancel($line);
        } catch (CancelNotAllowedException $e) {
            Flash::error($e->getMessage());
            return redirect(route('credit_lines.show', ['line' => $line->id]));
        }

        Flash::success('Credit line cancelled.');

        return redirect(route('credit_lines.show', ['line' => $line->id]));
    }

    /**
     * Phase 9: payment simulator — read-only "what if" projection.
     *
     * Admin-gated. Renders the simulator view. If a positive
     * `monthly_payment_usd` is supplied via the query string, runs the
     * three-scenario simulation (conservative / expected / aggressive)
     * and passes the results to the view; otherwise renders the form
     * with no results.
     */
    public function simulator($id, Request $request, PaymentSimulator $simulator)
    {
        $this->ensureAdmin();

        $line = AccountCreditLineExt::findOrFail($id);
        $this->authorize('process', $line);
        $account = $line->account()->first();

        $currentShareValue = null;
        try {
            $currentShareValue = $account
                ? (float) $account->shareValueAsOf(Carbon::today()->toDateString())
                : null;
        } catch (\Throwable $e) {
            $currentShareValue = null;
        }

        $mode = $request->query('mode', 'payment');
        if (!in_array($mode, ['payment', 'time'], true)) {
            $mode = 'payment';
        }

        $monthlyPaymentUsd = $request->query('monthly_payment_usd');
        $targetMonths = $request->query('target_months');
        $results = [];
        $solvedPayments = [];
        $error = null;

        if ($mode === 'time') {
            if ($targetMonths !== null && $targetMonths !== '') {
                $targetMonths = (int) $targetMonths;
                if ($targetMonths < 1 || $targetMonths > 600) {
                    $error = 'target_months must be between 1 and 600';
                } else {
                    try {
                        $all = $simulator->solveForPaymentAllScenarios($line, $targetMonths);
                        foreach ($all as $k => $row) {
                            $results[$k] = $row['result'];
                            $solvedPayments[$k] = $row['payment'];
                        }
                    } catch (InvalidArgumentException $e) {
                        $error = $e->getMessage();
                    }
                }
            } else {
                $targetMonths = null;
            }
        } else {
            if ($monthlyPaymentUsd !== null && $monthlyPaymentUsd !== '') {
                $monthlyPaymentUsd = (float) $monthlyPaymentUsd;
                try {
                    $results = $simulator->simulateAllScenarios($line, $monthlyPaymentUsd);
                } catch (InvalidArgumentException $e) {
                    $error = $e->getMessage();
                }
            } else {
                $monthlyPaymentUsd = null;
            }
        }

        return view('account_credit_lines.simulator')
            ->with('line', $line)
            ->with('account', $account)
            ->with('currentShareValue', $currentShareValue)
            ->with('mode', $mode)
            ->with('monthlyPaymentUsd', is_numeric($monthlyPaymentUsd) ? (float) $monthlyPaymentUsd : null)
            ->with('targetMonths', is_numeric($targetMonths) ? (int) $targetMonths : null)
            ->with('results', $results)
            ->with('solvedPayments', $solvedPayments)
            ->with('simError', $error);
    }
