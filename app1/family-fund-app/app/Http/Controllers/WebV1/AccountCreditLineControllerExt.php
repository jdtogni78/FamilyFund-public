    /**
     * Global (cross-account) open/late receivables listing. Admin-only.
     *
     * Shows every schedule row that is still open (scheduled / partial /
     * late) so the operator can see — and reconcile — the outstanding
     * backlog, including rows generated by backdated draws.
     */
    public function globalPayments(Request $request)
    {
        $this->ensureAdmin();

        $openStatuses = [
            CreditLinePayment::STATUS_SCHEDULED,
            CreditLinePayment::STATUS_PARTIAL,
            CreditLinePayment::STATUS_LATE,
        ];

        $allStatuses = [
            CreditLinePayment::STATUS_SCHEDULED,
            CreditLinePayment::STATUS_PARTIAL,
            CreditLinePayment::STATUS_LATE,
            CreditLinePayment::STATUS_PAID,
            CreditLinePayment::STATUS_CANCELLED,
        ];

        // 'open' (default) keeps the original open-receivables view; a
        // specific status narrows to it; 'all' shows everything.
        $status    = $request->query('status', 'open');
        $accountId = $request->query('account_id');
        $fundId    = $request->query('fund_id');
        $nickname  = trim((string) $request->query('nickname', ''));

        $query = CreditLinePayment::with(['creditLine.account.fund'])
            ->orderBy('due_date');

        if ($status === 'open') {
            $query->whereIn('status', $openStatuses);
        } elseif ($status !== 'all') {
            $query->where('status', $status);
        }

        if ($nickname !== '') {
            $query->whereHas('creditLine', fn ($q) => $q->where('nickname', 'like', '%' . $nickname . '%'));
        }
        if ($accountId) {
            $query->whereHas('creditLine', fn ($q) => $q->where('account_id', $accountId));
        }
        if ($fundId) {
            $query->whereHas('creditLine.account', fn ($q) => $q->where('fund_id', $fundId));
        }

        // Filter option lists: only accounts/funds that actually have
        // credit lines, so the dropdowns stay scoped to relevant choices.
        $accounts = AccountExt::whereIn('id', AccountCreditLine::query()->select('account_id'))
            ->with('fund')
            ->orderBy('nickname')
            ->get();
        $funds = $accounts->pluck('fund')
            ->filter()
            ->unique('id')
            ->sortBy('name')
            ->values();

        return view('account_credit_lines.global_payments')
            ->with('payments', $query->get())
            ->with('status', $status)
            ->with('statusOptions', $allStatuses)
            ->with('accounts', $accounts)
            ->with('funds', $funds)
            ->with('accountId', $accountId)
            ->with('fundId', $fundId)
            ->with('nickname', $nickname)
            ->with('today', Carbon::today());
    }

    public function create($accountId, OutstandingCalculator $calculator)
    {
        $this->ensureAdmin();
        $account = AccountExt::findOrFail($accountId);
        $this->authorize('create', [AccountCreditLineExt::class, $account]);

        $available = $calculator->availableToBorrow($account, Carbon::today());

